/**
 * Prints every computed value and writes numbers.md + voiceover_script.txt.
 *   npm run numbers
 */
import { writeFileSync } from "node:fs";
import { D, N, S, usd, usdRound } from "../src/numbers";
import { DISCLOSURE_FIRM_LINE, DISCLOSURE_TEXT, SCRIPT, stripMarks } from "../src/script";
import { TAX_CONFIG as T } from "../src/taxModel";
import { SCENES, SCENE_TIMING, TOTAL_SECONDS } from "../src/timeline";

type Row = [string, string, string];
const table = (head: Row, rows: Row[]) =>
  [head, ["---", "---", "---"] as Row, ...rows].map((r) => `| ${r.join(" | ")} |`).join("\n");

const inputs: Row[] = [
  ["Filing status / tax year", `${T.filingStatus}, ${T.taxYear}`, ""],
  ["W-2 income", usd(S.w2Income), ""],
  ["ISOs", S.isoCount.toLocaleString("en-US"), D.isoCount],
  ["Strike", usd(S.strike), D.strike],
  ["Current FMV (hypothetical)", usd(S.fmv), D.fmv],
  ["Standard deduction", usd(T.standardDeduction), ""],
  ["AMT exemption", usd(T.amtExemption), ""],
  ["AMT exemption phase-out starts at AMTI of", usd(T.amtPhaseOutStart), ""],
  ["AMT phase-out rate", `${T.amtPhaseOutRate * 100}%`, ""],
  ["AMT rates", `${T.amtRateLow * 100}% / ${T.amtRateHigh * 100}% above ${usd(T.amtRateBreak)}`, ""],
  [
    "Regular brackets (taxable income up to)",
    T.regularBrackets.map((b) => `${b.rate * 100}%: ${b.upTo === Infinity ? "above" : usd(b.upTo)}`).join("; "),
    "",
  ],
];

const results: Row[] = [
  ["Spread per option (FMV - strike)", usd(N.spreadPerShare), D.spreadPerShare],
  ["Total spread", usd(N.totalSpread), D.totalSpread],
  ["Cash to exercise all (strike x count)", usd(N.exerciseCost), "not shown"],
  ["Regular tax, wages only", usd(N.regular), "chart line only"],
  ["Tentative minimum tax, no exercise", usd(N.tmtNoExercise), "chart line only"],
  ["(a) TMT if all exercised this year", usd(N.allAtOnce.tmt), "not shown"],
  ["(a) AMT if all exercised this year", usd(N.allAtOnce.amt), `roughly ${D.amtAll}`],
  ["(b) Crossover spread (about $0 AMT)", usd(N.crossover.spread), `about ${D.crossoverSpread}`],
  ["(b) Crossover in whole options", N.crossover.shares.toLocaleString("en-US"), `roughly ${D.crossoverShares}`],
  [`(c) Staggered: options exercised over ${S.staggerYears} years`, N.staggeredShares.toLocaleString("en-US"), `~${D.staggeredShares}`],
  ["(c) Staggered: spread recognized", usd(N.staggeredSpread), "not shown"],
  ["(c) Staggered: total AMT", usd(N.staggeredAmt), `~${D.staggeredAmt}`],
  [`Contrast: even split (${(S.isoCount / S.staggerYears).toLocaleString("en-US")}/yr), AMT per year`, usd(N.evenSplit[0].amt), "not shown"],
  ["Contrast: even split, total AMT", usd(N.evenSplitAmt), "not shown"],
  ["AMT credit usable per later year (regular tax - TMT, no sale)", usd(N.creditPerYear), `roughly ${D.creditPerYear} a year`],
  ["Credit recovered after 8 later years", usd(N.creditPerYear * 8), `~${usdRound(N.creditPerYear * 8)}`],
  ["Years to recover the full credit at that pace", N.creditYears.toFixed(1), "not shown"],
];

const schedule = [
  "| Year | Options exercised | Spread | Regular tax | Tentative minimum tax | AMT owed |",
  "| --- | --- | --- | --- | --- | --- |",
  ...N.staggered.map(
    (r) => `| ${r.year} | ${r.shares} | ${usd(r.spread)} | ${usd(r.regularTax)} | ${usd(r.tmt)} | ${usd(r.amt)} |`,
  ),
  `| Total | ${N.staggeredShares.toLocaleString("en-US")} | ${usd(N.staggeredSpread)} | | | ${usd(N.staggeredAmt)} |`,
].join("\n");

const md = `# ISO / AMT explainer: computed numbers

Generated by \`npm run numbers\` from \`src/taxModel.ts\`. Do not edit by hand.
Every figure in the video is read from this model. All values are hypothetical and simplified.

## Inputs (FRANK: VERIFY each one)

${table(["Input", "Value", "On screen"], inputs)}

## Results

${table(["Item", "Exact (model)", "On screen (rounded)"], results)}

## Staggered schedule (each year sized at that year's crossover)

${schedule}

## What the model leaves out

- Federal only. No state tax (California has its own AMT), no NIIT, no payroll tax.
- Single filer, standard deduction, wages as the only other income, no other AMT preference items.
- Income, FMV, and tax parameters are held flat across the ${S.staggerYears} schedule years. In practice the thresholds index each year and the FMV moves, so each year's crossover is different.
- Credit recovery assumes no sale. A later sale of the shares creates a negative AMT adjustment that can speed up recovery; a price drop can strand part of the credit.
- ISO expiration (10 years from grant, and usually 90 days after leaving) is not modeled.

## Two things worth knowing before you post

1. The crossover is small relative to the grant: about ${D.crossoverShares} options a year against ${D.isoCount}. The video says so on screen (~${D.staggeredShares} of ${D.isoCount} in ${S.staggerYears} years).
2. Splitting all ${D.isoCount} evenly over ${S.staggerYears} years does not reduce AMT in this model: ${usd(N.evenSplitAmt)} total versus ${usd(N.allAtOnce.amt)} all at once, because each year is far past the crossover and the exemption is fully phased out. That is why the video sizes years to the crossover instead of splitting evenly.
`;

const stamp = (sec: number) => {
  const m = Math.floor(sec / 60);
  const s = sec - m * 60;
  return `${String(m).padStart(2, "0")}:${s.toFixed(1).padStart(4, "0")}`;
};
const vo: string[] = [
  "ISO / AMT EXPLAINER - VOICEOVER SCRIPT",
  `Total runtime ${stamp(TOTAL_SECONDS)}. Times are start - end in the finished video.`,
  "Generated by `npm run numbers` from src/script.ts and src/timeline.ts.",
  "",
];
SCENES.forEach(({ id }, i) => {
  const t = SCENE_TIMING[id];
  vo.push(`SCENE ${i + 1}: ${id.toUpperCase()}  [${stamp(t.startSec)} - ${stamp(t.startSec + t.seconds)}]`);
  for (const l of SCRIPT[id]) vo.push(`  ${stamp(t.startSec + l.at)} - ${stamp(t.startSec + l.to)}  ${stripMarks(l.text)}`);
  if (id === "disclosure") {
    vo.push("  (No narration. On-screen text, held for the full scene:)");
    vo.push(`  ${DISCLOSURE_TEXT}`);
    if (DISCLOSURE_FIRM_LINE) vo.push(`  ${DISCLOSURE_FIRM_LINE}`);
  }
  vo.push("");
});

writeFileSync("numbers.md", md);
writeFileSync("voiceover_script.txt", vo.join("\n"));
console.log(md);
console.log("wrote numbers.md and voiceover_script.txt");
