/**
 * Prints the ESPP model's values and writes numbers_espp.md and
 * voiceover_script_espp.txt.   npm run numbers:espp
 */
import { writeFileSync } from "node:fs";
import { D, E, ESPP } from "../src/espp/model";
import { DISCLOSURE_FIRM_LINE, DISCLOSURE_TEXT } from "../src/espp/script";
import { LINES, SCENES, SCENE_TIMING, TOTAL_SECONDS } from "../src/espp/timeline";
import { stripMarks } from "../src/lib/buildTimeline";

const usd = (n: number) => "$" + n.toFixed(2);
const row = (r: string[]) => `| ${r.join(" | ")} |`;
const md = `# ESPP explainer: computed numbers

Generated by \`npm run numbers:espp\` from \`src/espp/model.ts\`. Do not edit by hand.
Hypothetical, per share, Section 423 qualified plan. The model splits the gain into
ordinary income and capital gain; it applies no tax rates.

## Inputs (FRANK: VERIFY each one)

${[
  ["Input", "Value"],
  ["---", "---"],
  ["Plan discount", D.discount],
  ["Lookback", ESPP.lookback ? "yes (lower of offering-date and purchase-date price)" : "no"],
  ["Price on the offering date", usd(ESPP.offeringPrice)],
  ["Price on the purchase date", usd(ESPP.purchasePrice)],
  ["Sale price", usd(ESPP.salePrice)],
  ["Offering period", `${ESPP.offeringMonths} months`],
  ["Qualifying holding periods", `more than ${ESPP.monthsFromOffering} months from the offering date and more than ${ESPP.monthsFromPurchase} months from the purchase date`],
  ["Example disqualifying sale", `month ${ESPP.disqualifyingSaleMonth} (${ESPP.disqualifyingSaleMonth - ESPP.offeringMonths} months after purchase)`],
]
  .map(row)
  .join("\n")}

## Results (per share)

${[
  ["Item", "How", "Value"],
  ["---", "---", "---"],
  ["Price paid", `${D.discount} off ${usd(E.basePrice)}`, usd(E.paid)],
  ["Total gain at sale", "sale price - price paid", usd(E.totalGain)],
  ["Disqualifying: ordinary income", "purchase-date price - price paid", usd(E.disqualifying.ordinary)],
  ["Disqualifying: capital gain", `sale price - purchase-date price (${E.disqualifying.longTerm ? "long" : "short"}-term)`, usd(E.disqualifying.capital)],
  ["Qualifying: ordinary income", `lesser of ${D.discount} x offering-date price (${usd(E.offeringDiscount)}) or the gain (${usd(E.totalGain)})`, usd(E.qualifying.ordinary)],
  ["Qualifying: long-term capital gain", "total gain - ordinary income", usd(E.qualifying.capital)],
  ["First month both holding periods are met", "later of the two clocks", `month ${E.qualifiesAtMonth}`],
]
  .map(row)
  .join("\n")}

## What the model leaves out

- Tax rates and dollars of tax. Only the character of the gain is shown.
- State tax, NIIT, and payroll taxes.
- Plans without a lookback, with a smaller discount, or with purchase limits (the $25,000 annual limit is not modeled).
- Sales below the price paid in a qualifying disposition (ordinary income is then zero and the loss is a capital loss).
- Non-qualified ESPPs, which are taxed at purchase.
`;

const stamp = (sec: number) => {
  const m = Math.floor(sec / 60);
  const s = sec - m * 60;
  return `${String(m).padStart(2, "0")}:${s.toFixed(1).padStart(4, "0")}`;
};
const vo: string[] = [
  "ESPP EXPLAINER - VOICEOVER SCRIPT",
  `Total runtime ${stamp(TOTAL_SECONDS)}. Times are start - end in the finished video.`,
  "Generated by `npm run numbers:espp` from src/espp/script.ts and timeline.ts.",
  "",
];
SCENES.forEach(({ id }, i) => {
  const t = SCENE_TIMING[id];
  vo.push(`SCENE ${i + 1}: ${id.toUpperCase()}  [${stamp(t.startSec)} - ${stamp(t.startSec + t.seconds)}]`);
  for (const l of LINES[id]) vo.push(`  ${stamp(t.startSec + l.at)} - ${stamp(t.startSec + l.at + l.speak)}  ${stripMarks(l.text)}`);
  if (id === "endcard") vo.push("  (On screen: Frank Alvarez | Tidemark Financial Partners | Equity comp for engineers.)");
  if (id === "disclosure") {
    vo.push("  (On-screen text, held for the full scene:)");
    vo.push(`  ${DISCLOSURE_TEXT}`);
    if (DISCLOSURE_FIRM_LINE) vo.push(`  ${DISCLOSURE_FIRM_LINE}`);
  }
  vo.push("");
});
writeFileSync("numbers_espp.md", md);
writeFileSync("voiceover_script_espp.txt", vo.join("\n"));
console.log(md);
