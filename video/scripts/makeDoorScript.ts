/**
 * Writes voiceover_script_door_sticker.txt (timed lines) for
 * "Loaded to the door sticker".   npm run script:door
 */
import { writeFileSync } from "node:fs";
import { stripMarks } from "../src/lib/buildTimeline";
import { COST_LINES, DISCLOSURE_FIRM_LINE, DISCLOSURE_TEXT } from "../src/doorSticker/script";
import { LINES, SCENES, SCENE_TIMING, TOTAL_SECONDS } from "../src/doorSticker/timeline";

const stamp = (sec: number) => {
  const m = Math.floor(sec / 60);
  const s = sec - m * 60;
  return `${String(m).padStart(2, "0")}:${s.toFixed(1).padStart(4, "0")}`;
};
const out: string[] = [
  "LOADED TO THE DOOR STICKER - VOICEOVER SCRIPT",
  `Total runtime ${stamp(TOTAL_SECONDS)}. Times are start - end in the finished video.`,
  "Generated by `npm run script:door` from src/doorSticker/script.ts and timeline.ts.",
  "",
];
SCENES.forEach(({ id }, i) => {
  const t = SCENE_TIMING[id];
  out.push(`SCENE ${i + 1}: ${id.toUpperCase()}  [${stamp(t.startSec)} - ${stamp(t.startSec + t.seconds)}]`);
  for (const l of LINES[id]) out.push(`  ${stamp(t.startSec + l.at)} - ${stamp(t.startSec + l.at + l.speak)}  ${stripMarks(l.text)}`);
  if (id === "cost") {
    out.push("  (On screen, one at a time:)");
    for (const c of COST_LINES) out.push(`    -> ${c}`);
  }
  if (id === "endcard") out.push("  (No narration. On screen: Frank Alvarez | Tidemark Financial Partners | Equity comp for engineers.)");
  if (id === "disclosure") {
    out.push("  (No narration. On-screen text, held for the full scene:)");
    out.push(`  ${DISCLOSURE_TEXT}`);
    if (DISCLOSURE_FIRM_LINE) out.push(`  ${DISCLOSURE_FIRM_LINE}`);
  }
  out.push("");
});
writeFileSync("voiceover_script_door_sticker.txt", out.join("\n"));
